"""
embedding.py — 조각(글)을 벡터(숫자)로 바꾼다.

    python3 embedding.py

split.py 가 만든 chunks/ 의 조각 하나하나를 숫자 목록으로 바꿔 vectors/ 에 저장한다.
조각이 105개면 벡터도 105개다.

숫자는 '의미축'마다 그 축의 표제어가 조각에 몇 번 나오는지 센 것이다.
진짜 임베딩 모델은 이런 축을 수천 개 가지고 있고 축의 이름을 사람이 모를 뿐,
글을 숫자 좌표로 바꾼다는 원리는 같다.
"""
from pathlib import Path

조각폴더 = Path("chunks")
벡터폴더 = Path("vectors")

# 이 사전이 곧 이 임베딩의 '지식'이다. 사전에 없는 말은 숫자가 되지 못한다.
# 진짜 모델은 이 사전을 사람이 쓰지 않고 대규모 학습으로 익힌다.
# '휴가'처럼 여러 축(연차·휴직·경조)에 두루 나오는 말은 축을 구분해주지
# 못하므로 사전에 넣지 않는다. index.py 의 흔한말과 같은 이유다.
의미축 = {
    "연차": ["연차", "반일"],
    "휴직경조": ["휴직", "경조", "돌봄", "복직"],
    "수당": ["수당", "임금", "가산", "지급"],
    "근로시간": ["근로", "시간", "연장", "야간", "휴게"],
    "승인": ["승인", "신청", "상신", "결재", "통보"],
    "재택": ["재택", "원격", "보안"],
    "출장": ["출장", "여비", "숙박", "교통", "일비"],
    "교육": ["교육", "훈련", "이수", "자격"],
    "징계": ["징계", "위반", "위원회", "해고", "감봉"],
}


def 벡터만들기(글: str) -> dict:
    """글 → {축: 표제어가 나온 횟수}. 질문도 조각도 같은 방식으로 숫자가 된다."""
    return {축: sum(글.count(표제어) for 표제어 in 표제어들)
            for 축, 표제어들 in 의미축.items()}


# ask_embed.py 가 위의 사전과 함수를 가져다 쓰므로, 실행부는 이 아래에 둔다.
if __name__ == "__main__":
    import sys

    조각들 = sorted(조각폴더.glob("*.md"))
    if not 조각들:
        sys.exit("chunks/ 가 비어 있습니다. 먼저 python3 split.py 를 실행하세요.")

    벡터폴더.mkdir(exist_ok=True)
    for 기존 in 벡터폴더.glob("*.tsv"):
        기존.unlink()

    # 첫 조각으로 변환 과정을 눈으로 보여준다
    본보기 = 조각들[0]
    본보기벡터 = 벡터만들기(본보기.read_text(encoding="utf-8"))
    print(f"조각 하나가 숫자가 되는 과정 ({본보기.name}):\n")
    for 축, 값 in 본보기벡터.items():
        표제어 = ",".join(의미축[축])
        print(f"  {축:<4} [{표제어}]")
        print(f"       → {값:>3}  {'█' * min(값, 40)}")
    print(f"\n  → 벡터: {list(본보기벡터.values())}")

    for 조각 in 조각들:
        벡터 = 벡터만들기(조각.read_text(encoding="utf-8"))
        내용 = "\n".join(f"{축}\t{값}" for 축, 값 in 벡터.items())
        (벡터폴더 / f"{조각.stem}.tsv").write_text(내용 + "\n", encoding="utf-8")

    print(f"\n조각 {len(조각들)}개 → 벡터 {len(조각들)}개 ({벡터폴더}/ 에 저장했습니다)")
    print("벡터 파일 하나를 메모장으로 열어 보세요. 글이 숫자가 되어 있습니다.")
